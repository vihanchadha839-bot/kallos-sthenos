import type { Category, Equip, Exercise, Muscle } from '../types';

const LOWER_CORE = new Set([
  'reverse-crunch', 'lying-leg-raise', 'flutter-kick', 'scissor-kick', 'dead-bug', 'superman', 'bird-dog', 'reverse-hyper',
]);

function x(
  id: string, name: string, cat: Category, muscles: string, equip: string, diff: number,
  mode: 'r' | 'h', chain: 'C' | 'O', anatomy: string, cues: string, mistakes: string,
  regression: string, progression: string,
): Exercise {
  return {
    id, name, cat,
    muscles: muscles.split(',') as Muscle[],
    equip: equip ? (equip.split(',') as Equip[]) : [],
    diff,
    mode: mode === 'h' ? 'hold' : 'reps',
    chain: chain === 'C' ? 'Closed' : 'Open',
    zone: cat === 'core' ? (LOWER_CORE.has(id) ? 'lower' : 'upper') : undefined,
    anatomy,
    cues: cues.split('|'),
    mistakes: mistakes.split('|'),
    regression, progression,
  };
}

